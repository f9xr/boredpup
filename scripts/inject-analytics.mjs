/* BoredPuP - put the Google Analytics tag on the hand-written pages.

   Same shape as scripts/inject-csp.mjs and for the same reason: one script per
   concern that can be re-run at any time, with an idempotent write, so the tag
   never depends on someone remembering to paste it into fifteen files.

   The pages under g/ are generated by scripts/build-game-pages.mjs with their
   markup and policy already baked in, so they are skipped entirely - see
   scripts/analytics.mjs for why the tag is scoped this way. Unlike the CSP
   injector, a g/ page is never updated here even if edited by hand: a tracker
   appearing on 6,704 generated pages would be a much worse surprise than a
   missing tag.

   Where it goes: last thing in <head>, after the stylesheets, because it is
   async and does not need to block anything. */

import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { analyticsBlock, analyticsBlockRe } from "./analytics.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

async function pages() {
  const out = [];
  const collect = async (dir, prefix) => {
    for (const f of await readdir(dir)) {
      if (f.endsWith(".html")) out.push(prefix ? join(prefix, f) : f);
    }
  };
  await collect(root, "");
  await collect(join(root, "pages"), "pages");
  return out;
}

async function main() {
  let changed = 0;
  for (const file of await pages()) {
    const p = join(root, file);
    let html = await readFile(p, "utf8");
    const prefix = file.split(/[\\/]/)[0] === "pages" ? "../" : "";
    const block = analyticsBlock(prefix);
    const existing = html.match(analyticsBlockRe());

    if (existing) {
      const next = html.replace(analyticsBlockRe(), block);
      if (next !== html) {
        await writeFile(p, next, "utf8");
        console.log(`  updated ${file}`);
        changed++;
      }
      continue;
    }

    const head = html.match(/<\/head>/i);
    if (!head) {
      console.error(`  SKIPPED ${file}: no </head> to insert before`);
      continue;
    }
    html = html.replace(head[0], `${block.replace(/\n$/, "")}\n${head[0]}`);
    await writeFile(p, html, "utf8");
    console.log(`  added analytics to ${file}`);
    changed++;
  }
  console.log(changed ? `Done, ${changed} page(s) updated ✓` : "Already in sync");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});